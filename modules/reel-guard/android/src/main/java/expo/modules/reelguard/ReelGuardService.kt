/**
 * Counts reels: notices when a configured app's reels player is on screen (by view ID), counts
 * one reel on entering it and one per settled swipe, and adds up the time spent there.
 *
 * Privacy: it only reads view IDs of the configured apps, never text or content, and stores
 * nothing but per-day numbers (ReelStore). Events from other apps are filtered out by Android.
 */
class ReelGuardService : AccessibilityService() {
  companion object {
    private const val TAG = "ReelGuard"
    private const val TICK_MS = 2_000L
    private const val SWIPE_GAP_MS = 800L // fallback when the pager doesn't report item indices
    private const val UNKNOWN_START = -2
    private const val SETTLE_MS = 1_500L // the player may swap in its first page while loading
    private const val NUDGE_MS = 3_500L
    private const val REPAUSE_EVERY = 5 // past the limit, pause again every few reels
    private const val YOUTUBE = "com.google.android.youtube"
    private const val INSTAGRAM = "com.instagram.android"
    // "Count in browsers": short-video pages, matched in the address bar's text only. The group is the
    // page's id (a new id = the next short); the app is where the count goes, so limits apply as in the app.
    private val WEB_SHORTS = listOf(
      Regex("""(?:^|[./])youtube\.com/shorts/([\w-]+)""", RegexOption.IGNORE_CASE) to YOUTUBE,
      Regex("""(?:^|[./])instagram\.com/reels?(?:/([\w-]+))?(?:[/?#]|$)""", RegexOption.IGNORE_CASE) to INSTAGRAM,
    )
    private const val PAUSE_URL = "quitengine://pause" // opens the app's Pause screen (React Navigation)
    private const val WIDGET_PROVIDER = ".widget.Streak" // generated by react-native-android-widget (app.json)

    @Volatile var instance: ReelGuardService? = null
  }

  private val handler = Handler(Looper.getMainLooper())
  private var rules: Map<String, ReelRule> = emptyMap()
  private var active: String? = null // package whose reels player is open right now
  private var lastTick = 0L
  private var lastScreenCheck = 0L
  private var lastSwipeAt = 0L
  private var lastIndex = UNKNOWN_START
  private var lastPage: Int? = null // identity of the reel page on screen (rules with page IDs)
  private var enteredAt = 0L
  private var inPip = false
  private var bubble: TextView? = null // live counter while watching reels (optional)
  private var lastBlockAt = 0L
  private var blockTries = 0
  private var lastStudyCheck = 0L
  private var misses = 0
  private var lastTallSig = "" // debug calibration only
  private var fallback = false // the current session was found by the reels tab label, not by view IDs
  private val debug by lazy { (applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE) != 0 }

  // "Pause before opening" and app opens: the watched app in front right now (null = something else).
  private var watched: Set<String> = emptySet()
  private var webRules: Map<String, WebRule> = emptyMap() // browsers, only with "count in browsers" on
  private var lastWebPage: String? = null
  private var via: String? = null // the browser the current short is in (null = the app itself)
  private var front: String? = null
  private var lastFrontCheck = 0L
  // While a watched app is in front, check every few seconds whether it still is: the window-change
  // event can fire mid-transition, and events from the launcher or other apps are filtered out.
  private val frontWatch = object : Runnable {
    override fun run() {
      if (front == null) return
      checkFront()
      if (front != null) handler.postDelayed(this, 3_000)
    }
  }
  private val gate by lazy { OpenGate(this) { pkg, open -> gateChoice(pkg, open) } }
  private val screenOff = object : BroadcastReceiver() {
    override fun onReceive(context: Context, intent: Intent) {
      front = null // unlocking straight into an app counts as opening it
      gate.hide()
    }
  }

  private val ticker = object : Runnable {
    override fun run() {
      val pkg = active ?: return
      val now = SystemClock.elapsedRealtime()
      ReelStore.addTime(this@ReelGuardService, pkg, now - lastTick, notify = false)
      lastTick = now
      val power = getSystemService(POWER_SERVICE) as PowerManager
      if (!power.isInteractive) exit()
      else if (isBlocked(pkg)) block(pkg) // e.g. a reel-free time started while scrolling
      else checkScreen()
      if (active != null) schedule()
    }
  }

  override fun onServiceConnected() {
    instance = this
    applyRules()
    ReelStore.prune(this)
    val filter = IntentFilter(Intent.ACTION_SCREEN_OFF)
    if (Build.VERSION.SDK_INT >= 33) registerReceiver(screenOff, filter, RECEIVER_NOT_EXPORTED) else registerReceiver(screenOff, filter)
  }

  /**
   * Reloads detection rules and "pause before opening" apps (also after JS sends new ones) and
   * listens only to those apps. Apps that are only in the pause list are never read: only the fact
   * that they came to the front is used.
   */
  fun applyRules() {
    rules = ReelStore.rules(this).associateBy { it.pkg }
    webRules = if (ReelStore.webOn(this)) ReelStore.WEB_RULES.associateBy { it.pkg } else emptyMap()
    watched = rules.keys + ReelStore.gateConfig(this)?.apps.orEmpty() + webRules.keys
    serviceInfo = serviceInfo?.apply { packageNames = watched.toTypedArray() }
    if (debug) dlog("watching $watched")
  }

  override fun onAccessibilityEvent(event: AccessibilityEvent) {
    // App switches (not tied to one package): check right away whether we left the reels player.
    if (event.eventType == AccessibilityEvent.TYPE_WINDOWS_CHANGED) {
      checkFront()
      if (front != null) handler.postDelayed({ checkFront() }, 700) // again once the transition settles
      if (active != null) checkScreen()
      return
    }
    val pkg = event.packageName?.toString() ?: return
    if (debug && event.eventType != AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED) {
      dlog("event ${AccessibilityEvent.eventTypeToString(event.eventType)} $pkg src=${event.source?.viewIdResourceName}")
    }
    if (pkg != front && pkg in watched && pkg !in webRules) { // opens are counted for apps, not browsers
      // Content changes fire constantly (e.g. a mini player in the background): check those at most ~1.4×/s.
      val now = SystemClock.elapsedRealtime()
      val state = event.eventType == AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED
      if (state || (event.eventType == AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED && now - lastFrontCheck >= 700)) {
        lastFrontCheck = now
        appInFront(pkg)
      }
    }
    if (pkg in webRules) {
      // Browsers: only the address bar is checked, at most twice a second.
      val now = SystemClock.elapsedRealtime()
      if (event.eventType == AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED || now - lastScreenCheck >= 500) checkScreen()
      return
    }
    val rule = rules[pkg] ?: return
    when (event.eventType) {
      AccessibilityEvent.TYPE_VIEW_SCROLLED -> onScrolled(event, pkg, rule)
      AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED -> {
        if (debug) logIds(pkg)
        checkScreen()
      }
      AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED -> {
        val now = SystemClock.elapsedRealtime()
        if (now - lastScreenCheck >= 500) checkScreen() // these fire constantly; check at most twice a second
      }
    }
    if (pkg == YOUTUBE) checkStudyVideo()
  }

  private fun onScrolled(event: AccessibilityEvent, pkg: String, rule: ReelRule) {
    val id = event.source?.viewIdResourceName?.substringAfter(":id/")
    if (debug) dlog("scroll $pkg id=$id from=${event.fromIndex} to=${event.toIndex} class=${event.className}")
    val known = id != null && id in rule.pagerIds
    // Backup mode: the pager's ID is unknown, so any full list/pager that moves to another item counts.
    val generic = !known && fallback && active == pkg && event.fromIndex >= 0 &&
      event.className?.toString()?.let { "RecyclerView" in it || "ViewPager" in it } == true
    if (!known && !generic) return
    if (known && active != pkg) enter(pkg)
    if (known && rule.pageIds.isNotEmpty()) return // counted by page changes instead (checkScreen)
    val from = event.fromIndex
    if (from >= 0) {
      if (from != event.toIndex) return // still between two reels
      if (lastIndex == UNKNOWN_START) lastIndex = from // the reel counted on entering
      else if (from != lastIndex) {
        lastIndex = from
        counted(pkg)
      }
    } else {
      val now = SystemClock.elapsedRealtime()
      if (now - lastSwipeAt > SWIPE_GAP_MS) counted(pkg)
      lastSwipeAt = now
    }
  }

  /** Is a configured app's reels player in the active window? Enters or leaves accordingly. */
  private fun checkScreen() {
    lastScreenCheck = SystemClock.elapsedRealtime()
    if (gate.showing) return // nothing counts while the pause asks first
    val apps = windows.filter { it.type == AccessibilityWindowInfo.TYPE_APPLICATION }
    // The app window the user is in. Its root is only readable for the configured apps.
    val root = apps.firstOrNull { it.isActive }?.root
    val pkg = root?.packageName?.toString()
    val rule = pkg?.let { rules[it] }
    val web = if (root != null && rule == null) pkg?.let { webRules[it] }?.let { webShort(root, it) } else null
    val byIds = root != null && rule != null && rule.screenIds.any { id ->
      root.findAccessibilityNodeInfosByViewId("$pkg:id/$id").isNotEmpty()
    }
    // Backup when the app changed its screens: its reels tab is the selected one in the bottom bar.
    val byTab = !byIds && root != null && rule != null && rule.tabs.isNotEmpty() && selectedTab(root, rule.tabs)
    val open = byIds || byTab
    val pipPkg = if (open || web != null) null else pipReels(apps)
    if (web != null) {
      // A short in a browser counts for its app (YouTube / Instagram): same limit, pauses and blocks.
      val (app, page) = web
      misses = 0
      inPip = false
      if (active != app && isBlocked(app)) return block(app)
      if (active != app || via != pkg) enter(app, pkg)
      trackWebPage(app, page)
    } else if (open) {
      misses = 0
      inPip = false
      if (active != pkg && isBlocked(pkg)) return block(pkg)
      if (active != pkg || via != null) {
        enter(pkg)
        fallback = byTab
        if (byTab) {
          ReelStore.markFallback(this, pkg)
          if (debug) dlog("fallback $pkg (tab label)")
        }
      }
      if (byIds && rule.pageIds.isNotEmpty()) trackPage(root, pkg, rule)
      if (byTab) trackGenericPage(root, pkg)
    } else if (pipPkg != null) {
      if (isBlocked(pipPkg)) return block(pipPkg)
      misses = 0 // still watching, in the floating window: time keeps counting
      if (active != pipPkg) enter(pipPkg)
      if (!inPip && debug) dlog("pip $pipPkg")
      inPip = true
      refreshBubble()
    } else if (active != null && ++misses >= 2) {
      exit() // two misses in a row, so a brief redraw doesn't end the session
    }
  }

  /**
   * A configured app playing reels in a picture-in-picture window. Instagram keeps a reel
   * playing in a floating window after Home; that time counts too.
   */
  private fun pipReels(apps: List<AccessibilityWindowInfo>): String? {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return null
    for (window in apps) {
      if (!window.isInPictureInPictureMode) continue
      val root = window.root ?: continue
      val pkg = root.packageName?.toString() ?: continue
      val rule = rules[pkg] ?: continue
      if (rule.pip || rule.screenIds.any { root.findAccessibilityNodeInfosByViewId("$pkg:id/$it").isNotEmpty() }) return pkg
    }
    return null
  }

  /**
   * Some apps (YouTube Shorts) send no scroll event per reel. There, a new reel is a different
   * page view filling the player. Only view identity and size are used, never content.
   */
  private fun trackPage(root: AccessibilityNodeInfo, pkg: String, rule: ReelRule) {
    val bounds = Rect()
    fun height(node: AccessibilityNodeInfo) = bounds.also { node.getBoundsInScreen(it) }.height()
    val pages = rule.pageIds.flatMap { root.findAccessibilityNodeInfosByViewId("$pkg:id/$it") }
    val page = pages.maxByOrNull(::height) ?: return
    val pager = rule.pagerIds.firstNotNullOfOrNull { root.findAccessibilityNodeInfosByViewId("$pkg:id/$it").firstOrNull() }
    if (pager != null && height(page) < height(pager) * 3 / 4) return // mid-swipe: wait until it settles
    val id = page.hashCode() // based on the view's identity, not its content
    val settling = SystemClock.elapsedRealtime() - enteredAt < SETTLE_MS
    when {
      lastPage == null || settling -> lastPage = id // still the reel counted on entering
      lastPage == id -> Unit
      else -> {
        lastPage = id
        counted(pkg)
        if (debug) dlog("next reel $pkg")
      }
    }
  }

  /**
   * Backup counting without view IDs: the largest scrolling container on screen is the reels pager,
   * and its biggest child is the reel on screen. A different child (view identity, not content) is the
   * next reel, like trackPage.
   */
  private fun trackGenericPage(root: AccessibilityNodeInfo, pkg: String) {
    val bounds = Rect()
    fun box(n: AccessibilityNodeInfo) = Rect().also { n.getBoundsInScreen(it) }
    var pager: AccessibilityNodeInfo? = null
    var best = 0L
    var seen = 0
    fun walk(n: AccessibilityNodeInfo?, depth: Int) {
      if (n == null || depth > 30 || ++seen > 400) return
      // Apps don't always mark their pager as scrollable (YouTube Shorts doesn't): lists and pagers by class too.
      val cls = n.className?.toString().orEmpty()
      if (n.isScrollable || "RecyclerView" in cls || "ViewPager" in cls) {
        val b = box(n)
        val area = b.width().toLong() * b.height()
        if (area >= best) { // ties: the deeper one (the reels list inside a full-screen tab pager)
          best = area
          pager = n
        }
      }
      for (i in 0 until n.childCount) walk(n.getChild(i), depth + 1)
    }
    walk(root, 0)
    if (debug) {
      // Calibration: full-height views (class, id, identity, depth), logged when the set changes.
      val screenH = box(root).height()
      val tall = mutableListOf<String>()
      var n2 = 0
      fun scan(n: AccessibilityNodeInfo?, depth: Int) {
        if (n == null || depth > 30 || ++n2 > 400) return
        if (box(n).height() >= screenH * 3 / 4) {
          tall += "${depth}:${n.className?.toString()?.substringAfterLast('.')}:${n.viewIdResourceName?.substringAfter(":id/") ?: "-"}:${n.hashCode()}${if (n.isScrollable) ":S" else ""}:c${n.childCount}"
        }
        for (i in 0 until n.childCount) scan(n.getChild(i), depth + 1)
      }
      scan(root, 0)
      val sig = tall.joinToString(" ")
      if (sig != lastTallSig) {
        lastTallSig = sig
        dlog("tall $sig")
      }
    }
    val p = pager ?: return
    val pagerHeight = box(p).height()
    var page: AccessibilityNodeInfo? = null
    var pageHeight = 0
    for (i in 0 until p.childCount) {
      val child = p.getChild(i) ?: continue
      val h = bounds.also { child.getBoundsInScreen(it) }.height()
      if (h > pageHeight) {
        pageHeight = h
        page = child
      }
    }
    val current = page ?: return
    if (pageHeight < pagerHeight * 3 / 4) return // mid-swipe: wait until it settles
    val id = current.hashCode()
    if (debug && id != lastPage) dlog("backup page in ${p.className} children=${p.childCount}")
    val settling = SystemClock.elapsedRealtime() - enteredAt < SETTLE_MS
    when {
      lastPage == null || settling -> lastPage = id
      lastPage == id -> Unit
      else -> {
        lastPage = id
        counted(pkg)
        if (debug) dlog("next reel $pkg (backup)")
      }
    }
  }

  /** A node labelled like the reels tab ("Reels", "Shorts"…) that is selected (or inside a selected one). */
  private fun selectedTab(root: AccessibilityNodeInfo, labels: List<String>): Boolean {
    var seen = 0
    fun walk(node: AccessibilityNodeInfo?, depth: Int, selectedAbove: Boolean): Boolean {
      if (node == null || depth > 30 || ++seen > 400) return false
      val selected = selectedAbove || node.isSelected
      val label = (node.contentDescription ?: node.text)?.toString()?.trim()
      if (selected && label != null && labels.any { it.equals(label, ignoreCase = true) }) return true
      for (i in 0 until node.childCount) if (walk(node.getChild(i), depth + 1, selected)) return true
      return false
    }
    return walk(root, 0, false)
  }

  /**
   * In a browser, the short-video page shown in the address bar: the app it counts for and the
   * page's id. Only the address bar's text is read (not while the user is typing in it), matched
   * here and never stored.
   */
  private fun webShort(root: AccessibilityNodeInfo, web: WebRule): Pair<String, String>? {
    val bar = web.urlIds.firstNotNullOfOrNull { root.findAccessibilityNodeInfosByViewId("${web.pkg}:id/$it").firstOrNull() }
      ?: return null
    if (bar.isFocused) return null
    val address = bar.text?.toString() ?: return null
    for ((re, app) in WEB_SHORTS) re.find(address)?.let { return app to (it.groupValues.getOrNull(1) ?: "") }
    return null
  }

  /** A browser shows each short at its own address: a new address is the next short. */
  private fun trackWebPage(app: String, page: String) {
    val settling = SystemClock.elapsedRealtime() - enteredAt < SETTLE_MS
    when {
      lastWebPage == null || settling -> lastWebPage = page // still the short counted on entering
      lastWebPage == page -> Unit
      else -> {
        lastWebPage = page
        counted(app)
        if (debug) dlog("next short $app (web)")
      }
    }
  }

  private fun enter(pkg: String, browser: String? = null) {
    if (active != null) exit()
    active = pkg
    via = browser
    fallback = false
    misses = 0
    lastIndex = UNKNOWN_START
    lastPage = null
    lastWebPage = null
    enteredAt = SystemClock.elapsedRealtime()
    lastTick = SystemClock.elapsedRealtime()
    counted(pkg) // the reel that is showing now
    schedule()
    refreshBubble()
    if (debug) dlog("enter $pkg${browser?.let { " via $it" } ?: ""}")
  }

  /** Exactly one pending tick while a reels player is open. */
  private fun schedule() {
    handler.removeCallbacks(ticker)
    handler.postDelayed(ticker, TICK_MS)
  }

  private fun exit() {
    val pkg = active ?: return
    handler.removeCallbacks(ticker)
    ReelStore.addTime(this, pkg, SystemClock.elapsedRealtime() - lastTick, notify = true)
    active = null
    via = null
    inPip = false
    refreshBubble()
    refreshWidget()
    if (debug) dlog("exit $pkg")
  }

  /**
   * After each reel, with a daily limit set: a gentle note at half and at 80% of the limit, and
   * the Pause screen when the limit is reached. Fixed rules, set by the user ("if X, do Y").
   */
  private fun counted(pkg: String) {
    if (isBlocked(pkg)) return block(pkg) // e.g. this app's daily limit was just reached
    val total = ReelStore.addReel(this, pkg)
    refreshBubble()
    val limit = ReelStore.limit(this)
    if (limit <= 0) return
    val allowed = limit + ReelStore.extraToday(this) // "5 more" moves this
    val last = ReelStore.pausedAt(this)
    if (total >= allowed && !ReelStore.pausesOffToday(this) && (last == 0 || total >= last + REPAUSE_EVERY)) {
      ReelStore.setPausedAt(this, total)
      openPause(pkg)
    } else if (total < limit && (total == (limit + 1) / 2 || total == (limit * 4 + 4) / 5)) {
      showNudge(ReelStore.nudgeText(this, total, limit))
    }
  }

  /**
   * Back first: it closes the reels player, so the app doesn't keep playing in a floating
   * window over the Pause screen (YouTube and Instagram do that when sent to the background).
   */
  private fun openPause(pkg: String) {
    hideBubble()
    performGlobalAction(GLOBAL_ACTION_BACK)
    val back = via ?: pkg // "back to the app" returns to the browser for a short watched there
    handler.postDelayed({ startPause(back) }, 350)
  }

  private fun startPause(pkg: String) {
    try {
      startActivity(
        Intent(Intent.ACTION_VIEW, Uri.parse("$PAUSE_URL?app=$pkg"))
          .setPackage(packageName)
          .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP),
      )
      if (debug) dlog("pause $pkg")
      // Some apps still float the video over the Pause screen; close that window if it appears.
      handler.postDelayed({ closeReelsPip() }, 700)
      handler.postDelayed({ closeReelsPip() }, 1_500)
    } catch (e: Exception) {
      if (debug) dlog("pause failed $e")
    }
  }

  /** Closes a configured app's picture-in-picture window (only used right after a pause). */
  private fun closeReelsPip() {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
    for (window in windows) {
      if (!window.isInPictureInPictureMode) continue
      val root = window.root ?: continue
      if (root.packageName?.toString() !in rules) continue
      val dismissed = root.performAction(AccessibilityNodeInfo.ACTION_DISMISS)
      if (debug) dlog("pip close ${root.packageName} dismissed=$dismissed actions=${root.actionList.map { it.id }}")
    }
  }

  private fun minuteNow() = Calendar.getInstance().let { it.get(Calendar.HOUR_OF_DAY) * 60 + it.get(Calendar.MINUTE) }
  private fun inWindow(minute: Int, w: Pair<Int, Int>) =
    if (w.first <= w.second) minute in w.first until w.second else minute >= w.first || minute < w.second

  /** YouTube study mode is on and active right now (always, or inside its time window). */
  private fun studyActive(): StudyConfig? {
    val study = ReelStore.blockConfig(this)?.study ?: return null
    return study.takeIf { it.always || (it.window != null && inWindow(minuteNow(), it.window)) }
  }

  /** Blocking rules (Premium): always for this app, exam mode, a reel-free time now, or its daily limit used up. */
  private fun isBlocked(pkg: String): Boolean {
    val cfg = ReelStore.blockConfig(this) ?: return false
    if (pkg in cfg.apps || System.currentTimeMillis() < cfg.until) return true
    if (cfg.windows.any { inWindow(minuteNow(), it) }) return true
    if (pkg == YOUTUBE && studyActive() != null) return true // study mode: no Shorts
    val limit = cfg.appLimits[pkg] ?: 0
    return limit > 0 && ReelStore.todayCount(this, pkg) >= limit
  }

  /**
   * Leaves the reels player (Back), closes a floating reel and shows the note. Nothing is counted.
   * A fixed rule the user set; at most 3 Backs in 10 s, so it never fights the user.
   */
  private fun block(pkg: String) {
    val now = SystemClock.elapsedRealtime()
    if (now - lastBlockAt < 1_500) return
    blockTries = if (now - lastBlockAt < 10_000) blockTries + 1 else 1
    lastBlockAt = now
    if (active != null) exit()
    hideBubble()
    if (blockTries <= 3) performGlobalAction(GLOBAL_ACTION_BACK)
    ReelStore.blockConfig(this)?.text?.takeIf { it.isNotEmpty() }?.let(::showNudge)
    handler.postDelayed({ closeReelsPip() }, 700)
    if (debug) dlog("block $pkg try=$blockTries")
  }

  /**
   * Study mode: on a YouTube video page, reads the channel name (only that view) and sends the
   * user back if it isn't one of their study channels. Never stored or sent anywhere.
   */
  private fun checkStudyVideo() {
    val now = SystemClock.elapsedRealtime()
    if (now - lastStudyCheck < 1_000) return
    lastStudyCheck = now
    val study = studyActive() ?: return
    val root = windows.firstOrNull { it.type == AccessibilityWindowInfo.TYPE_APPLICATION && it.isActive }?.root ?: return
    if (root.packageName?.toString() != YOUTUBE) return
    if (study.watchIds.none { root.findAccessibilityNodeInfosByViewId("$YOUTUBE:id/$it").isNotEmpty() }) return
    val name = currentChannel(root, study.prefixes)
      ?: return // channel row not on screen yet, covered, or another language: never block blindly
    val allowed = study.channels.any { name.contains(it) || it.contains(name) }
    if (debug) dlog("study video allowed=$allowed")
    if (allowed) return
    blockVideo(study.text)
  }

  /**
   * The open video's channel, from the first Subscribe button label on the page ("Subscribe to X.").
   * Other labels are only compared against the prefixes, never kept.
   */
  private fun currentChannel(root: AccessibilityNodeInfo, prefixes: List<String>): String? {
    fun walk(node: AccessibilityNodeInfo?, depth: Int): String? {
      if (node == null || depth > 40) return null
      val label = node.contentDescription?.toString()
      if (label != null) {
        prefixes.firstOrNull { label.startsWith(it, ignoreCase = true) }?.let { prefix ->
          return ReelStore.channelKey(label.substring(prefix.length).trimEnd('.', ' '))
        }
      }
      for (i in 0 until node.childCount) walk(node.getChild(i), depth + 1)?.let { return it }
      return null
    }
    return walk(root, 0)?.takeIf { it.isNotEmpty() }
  }

  /** Leaves a non-study video: Back, then pause, since YouTube keeps playing in its mini player. */
  private fun blockVideo(text: String) {
    val now = SystemClock.elapsedRealtime()
    if (now - lastBlockAt < 1_500) return
    lastBlockAt = now
    performGlobalAction(GLOBAL_ACTION_BACK)
    handler.postDelayed({
      val audio = getSystemService(AUDIO_SERVICE) as android.media.AudioManager
      audio.dispatchMediaKeyEvent(android.view.KeyEvent(android.view.KeyEvent.ACTION_DOWN, android.view.KeyEvent.KEYCODE_MEDIA_PAUSE))
      audio.dispatchMediaKeyEvent(android.view.KeyEvent(android.view.KeyEvent.ACTION_UP, android.view.KeyEvent.KEYCODE_MEDIA_PAUSE))
    }, 400)
    if (text.isNotEmpty()) showNudge(text)
    handler.postDelayed({ closeReelsPip() }, 700)
    if (debug) dlog("study block")
  }

  /** Shows, updates or hides the live counter: visible only while a reels player is on screen. */
  fun refreshBubble() {
    if (active == null || inPip || !ReelStore.bubbleOn(this)) return hideBubble()
    val text = ReelStore.bubbleText(this, ReelStore.todayTotal(this))
    bubble?.let { it.text = text; return }
    try {
      val wm = getSystemService(WINDOW_SERVICE) as WindowManager
      fun dp(v: Float) = TypedValue.applyDimension(TypedValue.COMPLEX_UNIT_DIP, v, resources.displayMetrics).toInt()
      val view = TextView(this).apply {
        this.text = text
        setTextColor(0xFFFFFFFF.toInt())
        setTextSize(TypedValue.COMPLEX_UNIT_SP, 13f)
        setPadding(dp(12f), dp(6f), dp(12f), dp(6f))
        background = GradientDrawable().apply {
          cornerRadius = dp(16f).toFloat()
          setColor(0xCC1D1B29.toInt()) // dark, slightly see-through: readable over any video
        }
      }
      val params = WindowManager.LayoutParams(
        WindowManager.LayoutParams.WRAP_CONTENT,
        WindowManager.LayoutParams.WRAP_CONTENT,
        WindowManager.LayoutParams.TYPE_ACCESSIBILITY_OVERLAY,
        WindowManager.LayoutParams.FLAG_NOT_FOCUSABLE or WindowManager.LayoutParams.FLAG_NOT_TOUCHABLE,
        PixelFormat.TRANSLUCENT,
      ).apply {
        gravity = Gravity.TOP or Gravity.END
        x = dp(12f)
        y = dp(110f)
      }
      wm.addView(view, params)
      bubble = view
    } catch (e: Exception) {
      if (debug) dlog("bubble failed $e")
    }
  }

  private fun hideBubble() {
    val view = bubble ?: return
    bubble = null
    runCatching { (getSystemService(WINDOW_SERVICE) as WindowManager).removeView(view) }
  }

  /** A small note at the top of the screen for a few seconds. Not touchable, so it never blocks the app. */
  private fun showNudge(text: String) {
    try {
      val wm = getSystemService(WINDOW_SERVICE) as WindowManager
      fun dp(v: Float) = TypedValue.applyDimension(TypedValue.COMPLEX_UNIT_DIP, v, resources.displayMetrics).toInt()
      val view = TextView(this).apply {
        this.text = text
        setTextColor(0xFFFFFFFF.toInt())
        setTextSize(TypedValue.COMPLEX_UNIT_SP, 15f)
        setPadding(dp(18f), dp(10f), dp(18f), dp(10f))
        background = GradientDrawable().apply {
          cornerRadius = dp(24f).toFloat()
          setColor(0xEB6C5CE7.toInt()) // brand purple, slightly see-through
        }
      }
      val params = WindowManager.LayoutParams(
        WindowManager.LayoutParams.WRAP_CONTENT,
        WindowManager.LayoutParams.WRAP_CONTENT,
        WindowManager.LayoutParams.TYPE_ACCESSIBILITY_OVERLAY,
        WindowManager.LayoutParams.FLAG_NOT_FOCUSABLE or WindowManager.LayoutParams.FLAG_NOT_TOUCHABLE,
        PixelFormat.TRANSLUCENT,
      ).apply {
        gravity = Gravity.TOP or Gravity.CENTER_HORIZONTAL
        y = dp(56f)
      }
      wm.addView(view, params)
      handler.postDelayed({ runCatching { wm.removeView(view) } }, NUDGE_MS)
      if (debug) dlog("nudge $text")
    } catch (e: Exception) {
      if (debug) dlog("nudge failed $e")
    }
  }

  /** The full-screen app on top (not a floating picture-in-picture window); null if we can't tell. */
  private fun topApp(): String? =
    windows.filter { it.type == AccessibilityWindowInfo.TYPE_APPLICATION && !(Build.VERSION.SDK_INT >= Build.VERSION_CODES.O && it.isInPictureInPictureMode) }
      .maxByOrNull { it.layer }?.root?.packageName?.toString()

  /** A watched app sent an event: if it really is in front now, that's an open. */
  private fun appInFront(pkg: String) {
    if (topApp() != pkg) return // e.g. its mini player, or a window behind
    front = pkg
    handler.removeCallbacks(frontWatch)
    handler.postDelayed(frontWatch, 3_000)
    val opens = ReelStore.addOpen(this, pkg)
    if (debug) dlog("open $pkg ($opens today)")
    val cfg = ReelStore.gateConfig(this) ?: return
    if (pkg !in cfg.apps || System.currentTimeMillis() < ReelStore.graceUntil(this, pkg)) return
    hideBubble()
    gate.show(pkg, cfg, opens)
    if (debug) dlog("gate $pkg")
  }

  /** On any window change: did the app in front change? Then the next visit is a new open. */
  private fun checkFront() {
    val f = front ?: return
    if (topApp() == f) return
    front = null
    if (gate.pkg == f) gate.hide()
  }

  /** The user's answer on the pause: open (no pause again for a while) or not now (home screen). */
  private fun gateChoice(pkg: String, open: Boolean) {
    val cfg = ReelStore.gateConfig(this)
    if (open) {
      ReelStore.setGrace(this, pkg, System.currentTimeMillis() + (cfg?.graceMin ?: 10) * 60_000L)
      if (debug) dlog("gate open $pkg")
    } else {
      ReelStore.addSkip(this, pkg)
      front = null
      performGlobalAction(GLOBAL_ACTION_HOME)
      if (debug) dlog("gate not now $pkg")
    }
  }

  /** Asks the home-screen widget to redraw (it shows today's reel count). */
  private fun refreshWidget() {
    try {
      val provider = ComponentName(this, packageName + WIDGET_PROVIDER)
      val ids = AppWidgetManager.getInstance(this).getAppWidgetIds(provider)
      if (ids.isEmpty()) return
      sendBroadcast(
        Intent(AppWidgetManager.ACTION_APPWIDGET_UPDATE)
          .setComponent(provider)
          .putExtra(AppWidgetManager.EXTRA_APPWIDGET_IDS, ids),
      )
    } catch (e: Exception) {
      if (debug) dlog("widget refresh failed $e")
    }
  }

  /** Debug builds: lists view IDs on screen, to find the right ones when an app changes. */
  private fun logIds(pkg: String) {
    val ids = sortedSetOf<String>()
    fun walk(node: AccessibilityNodeInfo?, depth: Int) {
      if (node == null || depth > 25 || ids.size > 120) return
      node.viewIdResourceName?.let { ids += it.substringAfter(":id/") }
      for (i in 0 until node.childCount) walk(node.getChild(i), depth + 1)
    }
    walk(rootInActiveWindow, 0)
    dlog("screen $pkg ids=$ids")
    // Calibration (debug builds only): short labels and whether they're selected (* = selected).
    val labels = mutableListOf<String>()
    fun labelWalk(node: AccessibilityNodeInfo?, depth: Int) {
      if (node == null || depth > 25 || labels.size > 60) return
      (node.contentDescription ?: node.text)?.toString()?.takeIf { it.length in 1..20 }?.let { labels += if (node.isSelected) "$it*" else it }
      for (i in 0 until node.childCount) labelWalk(node.getChild(i), depth + 1)
    }
    labelWalk(rootInActiveWindow, 0)
    dlog("labels $pkg $labels")
  }

  /**
   * Debug builds only: logcat plus a small file in app storage (some phones, e.g. vivo, hide app
   * logs). Read with: adb shell run-as com.quitengine.app cat files/reel_guard_debug.log
   * Contains view IDs and event types only, never screen text.
   */
  private fun dlog(message: String) {
    Log.i(TAG, message)
    try {
      val file = java.io.File(filesDir, "reel_guard_debug.log")
      if (file.length() > 200_000) file.delete()
      file.appendText("${System.currentTimeMillis()} $message\n")
    } catch (e: Exception) {
      Log.w(TAG, "debug log failed", e)
    }
  }

  override fun onInterrupt() {}

  override fun onDestroy() {
    exit()
    hideBubble()
    gate.hide()
    handler.removeCallbacks(frontWatch)
    runCatching { unregisterReceiver(screenOff) }
    instance = null
    super.onDestroy()
  }
